// catalogFor returns the report vocabulary for one normalized language.
func catalogFor(language string) labels {
	if NormalizeLanguage(language) == LanguageChinese {
		return chineseLabels
	}
	return englishLabels
}

// NormalizeLanguage reduces a requested tag to the catalog the renderer has.
// Empty, an unknown tag and any English or Chinese variant read as one of the
// two supported languages, which mirrors the notification renderer.
func NormalizeLanguage(tag string) string {
	switch strings.ToLower(strings.TrimSpace(tag)) {
	case "zh", "zh-cn", "zh-hans", "zh-sg", "zh-tw", "zh-hant", "zh-hk":
		return LanguageChinese
	default:
		return LanguageEnglish
	}
}

