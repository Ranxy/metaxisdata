// humanizeEnum is the fallback for a key the catalog does not know: it removes
// the underscores so an unknown enum still renders readable text.
func humanizeEnum(key string) string {
	if key == "" {
		return ""
	}
	return strings.ReplaceAll(key, "_", " ")
}

// cssKey turns an enum key into a CSS class suffix.
func cssKey(key string) string {
	return strings.ToLower(strings.ReplaceAll(key, " ", "_"))
}

// formatObserved renders one observation with its unit.
func formatObserved(language string, value *float64, kindKey string) string {
	if value == nil {
		return englishLabels.LabelNotAvailable
	}
	text := strconv.FormatFloat(*value, 'f', -1, 64)
	switch kindKey {
	case "COUNT":
		if language == LanguageChinese {
			return text + " 行"
		}
		return text + " rows"
	case "RATIO":
		return text + "%"
	case "SECONDS":
		if language == LanguageChinese {
			return text + " 秒"
		}
		return text + "s"
	case "TIMESTAMP":
		return time.Unix(int64(*value), 0).UTC().Format("2006-01-02 15:04:05")
	case "NUMBER", "UNSPECIFIED", "":
		return text
	default:
		return text
	}
}

// formatThresholds renders one snapshot of the applied thresholds. Only the
// levels the rule set are shown; a rule with no threshold has no text at all.
func formatThresholds(language string, th *storepb.QualityThresholds) string {
	if th == nil {
		return ""
	}
	warn, fail, outside, inside := "warn", "fail", "outside", "inside"
	if language == LanguageChinese {
		warn, fail, outside, inside = "警告", "失败", "超出", "位于"
	}
	parts := make([]string, 0, 2)
	switch th.GetComparison() {
	case storepb.QualityComparison_QUALITY_COMPARISON_GREATER_THAN:
		parts = append(parts, thresholdPart(warn, ">", th.WarnValue), thresholdPart(fail, ">", th.FailValue))
	case storepb.QualityComparison_QUALITY_COMPARISON_LESS_THAN:
		parts = append(parts, thresholdPart(warn, "<", th.WarnValue), thresholdPart(fail, "<", th.FailValue))
	case storepb.QualityComparison_QUALITY_COMPARISON_OUTSIDE_RANGE:
		parts = append(parts, rangeThresholdPart(warn, outside, th.WarnValue, th.WarnValueUpper),
			rangeThresholdPart(fail, outside, th.FailValue, th.FailValueUpper))
	case storepb.QualityComparison_QUALITY_COMPARISON_INSIDE_RANGE:
		parts = append(parts, rangeThresholdPart(warn, inside, th.WarnValue, th.WarnValueUpper),
			rangeThresholdPart(fail, inside, th.FailValue, th.FailValueUpper))
	case storepb.QualityComparison_QUALITY_COMPARISON_UNSPECIFIED:
	default:
	}
	return strings.Join(parts, " · ")
}

// thresholdPart renders "warn > 5", or nothing when the level is unset.
func thresholdPart(level, operator string, value *float64) string {
	if value == nil {
		return ""
	}
	return level + " " + operator + " " + strconv.FormatFloat(*value, 'f', -1, 64)
}

// rangeThresholdPart renders "fail outside [1, 10]", or nothing when unset.
func rangeThresholdPart(level, relation string, lower, upper *float64) string {
	if lower == nil || upper == nil {
		return ""
	}
	return level + " " + relation + " [" +
		strconv.FormatFloat(*lower, 'f', -1, 64) + ", " +
		strconv.FormatFloat(*upper, 'f', -1, 64) + "]"
}

// formatInterval renders a schedule interval in its largest whole unit.
func formatInterval(language string, interval time.Duration) string {
	if interval <= 0 {
		return ""
	}
	units := [4]string{"s", "m", "h", "d"}
	if language == LanguageChinese {
		units = [4]string{"秒", "分钟", "小时", "天"}
	}
	number := ""
	switch {
	case interval < time.Minute:
		number = strconv.FormatInt(int64(interval/time.Second), 10)
		return number + units[0]
	case interval < time.Hour:
		number = strconv.FormatInt(int64(interval/time.Minute), 10)
		return number + units[1]
	case interval < 24*time.Hour:
		number = strconv.FormatFloat(interval.Hours(), 'f', -1, 64)
		return number + units[2]
	default:
		number = strconv.FormatFloat(interval.Hours()/24, 'f', -1, 64)
		return number + units[3]
	}
}
